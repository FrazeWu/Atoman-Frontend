import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises } from '@vue/test-utils'
import * as api from '@/api/bookReading'
import { ApiErrorResponseError } from '@/api/client'
import { useRevisionReading } from '@/composables/useRevisionReading'
import type { CloudReadingState, ReadingPosition } from '@/api/bookReading'

const cloud: CloudReadingState = { revision_id: 'rev-1', version: 3, epub_cfi: '', pdf_page: 0, txt_offset: 600, current_percent: .6, furthest_percent: .8 }
const position = (percent: number): ReadingPosition => ({ current_percent: percent, txt_offset: percent * 1000, epub_cfi: '', pdf_page: 0 })
let readers: ReturnType<typeof useRevisionReading>[] = []
const make = (owner = 'user-1', revision = 'rev-1') => { const reader = useRevisionReading(owner, revision); readers.push(reader); return reader }
beforeEach(() => {
  vi.useFakeTimers()
  localStorage.clear()
  vi.spyOn(api, 'createReadingSession').mockResolvedValue({ session: { id: 'session-1', last_sequence: 0, heartbeat_sequence: 0 }, state: cloud })
  vi.spyOn(api, 'getCloudReadingState').mockResolvedValue(cloud)
  vi.spyOn(api, 'saveCloudReadingState').mockImplementation(async (_, input) => ({ state: { ...cloud, ...input, version: input.base_version + 1 }, position_applied: true, duplicate: false }))
  vi.spyOn(api, 'sendReadingHeartbeat').mockResolvedValue({})
})
afterEach(() => { readers.forEach(reader => reader.dispose()); readers = []; vi.useRealTimers(); vi.restoreAllMocks() })

describe('修订级云阅读同步', () => {
  it('以云端当前进度初始化，不用最远进度代替当前位置，也不在打开时自动回写', async () => {
    const reader = make()
    expect(await reader.start()).toBe(true)
    expect(reader.initialPosition.value?.current_percent).toBe(.6)
    expect(api.saveCloudReadingState).not.toHaveBeenCalled()
  })
  it('合并连续翻页，允许回读，保留最远进度', async () => {
    const reader = make()
    await reader.start()
    reader.observe(position(.7))
    reader.observe(position(.2))
    await vi.advanceTimersByTimeAsync(800)
    expect(api.saveCloudReadingState).toHaveBeenCalledTimes(1)
    expect(api.saveCloudReadingState).toHaveBeenCalledWith('rev-1', expect.objectContaining({ current_percent: .2, txt_offset: 200, furthest_percent: .8, base_version: 3, sequence: 1 }), expect.any(AbortSignal))
    expect(reader.status.value).toBe('saved')
  })
  it('网络失败重试完全相同的请求收据，不递增序号或更换 request_id', async () => {
    vi.mocked(api.saveCloudReadingState).mockRejectedValueOnce(new Error('offline'))
    const reader = make()
    await reader.start()
    reader.observe(position(.4))
    await reader.flush()
    const first = { ...vi.mocked(api.saveCloudReadingState).mock.calls[0]![1] }
    expect(reader.status.value).toBe('offline')
    expect(localStorage.getItem('atoman:book-reading-outbox:user-1:rev-1')).toContain(first.request_id)
    await reader.flush()
    expect(vi.mocked(api.saveCloudReadingState).mock.calls[1]![1]).toEqual(first)
    expect(reader.status.value).toBe('saved')
  })
  it('请求在途时串行保留最新位置，下一次使用返回的版本', async () => {
    let resolve!: (result: Awaited<ReturnType<typeof api.saveCloudReadingState>>) => void
    vi.mocked(api.saveCloudReadingState).mockImplementationOnce(() => new Promise(done => { resolve = done }))
    const reader = make()
    await reader.start()
    reader.observe(position(.4))
    const saving = reader.flush()
    reader.observe(position(.5))
    reader.observe(position(.9))
    expect(api.saveCloudReadingState).toHaveBeenCalledTimes(1)
    resolve({ state: { ...cloud, ...position(.4), version: 4 }, position_applied: true, duplicate: false })
    await saving
    await flushPromises()
    expect(api.saveCloudReadingState).toHaveBeenCalledTimes(2)
    expect(vi.mocked(api.saveCloudReadingState).mock.calls[1]![1]).toMatchObject({ current_percent: .9, base_version: 4, sequence: 2 })
  })
  it('冲突后不自动重试覆盖；选择本机才基于新云版本保存', async () => {
    vi.mocked(api.saveCloudReadingState).mockRejectedValueOnce(new ApiErrorResponseError(409, 'books.reading_state_conflict', 'changed'))
    vi.mocked(api.getCloudReadingState).mockResolvedValue({ ...cloud, version: 10, current_percent: .9, furthest_percent: .9 })
    const reader = make()
    await reader.start()
    reader.observe(position(.2))
    await reader.flush()
    expect(reader.status.value).toBe('conflict')
    reader.observe(position(.3))
    await vi.advanceTimersByTimeAsync(2000)
    expect(api.saveCloudReadingState).toHaveBeenCalledTimes(1)
    reader.chooseLocal()
    await flushPromises()
    expect(vi.mocked(api.saveCloudReadingState).mock.calls[1]![1]).toMatchObject({ current_percent: .3, base_version: 10, furthest_percent: .9 })
  })
  it('选择云端时清理未同步位置，不再上传冲突旧值', async () => {
    vi.mocked(api.saveCloudReadingState).mockRejectedValueOnce(new ApiErrorResponseError(409, 'books.reading_state_conflict', 'changed'))
    const reader = make()
    await reader.start()
    reader.observe(position(.2))
    await reader.flush()
    reader.chooseCloud()
    await reader.flush()
    expect(reader.initialPosition.value?.current_percent).toBe(.6)
    expect(api.saveCloudReadingState).toHaveBeenCalledTimes(1)
    expect(localStorage.getItem('atoman:book-reading-outbox:user-1:rev-1')).toBeNull()
  })
  it('刷新重放原会话的在途请求，不丢失服务端已接受但响应丢失的写入', async () => {
    vi.mocked(api.saveCloudReadingState).mockRejectedValueOnce(new Error('lost response'))
    const first = make()
    await first.start()
    first.observe(position(.4))
    await first.flush()
    const original = { ...vi.mocked(api.saveCloudReadingState).mock.calls[0]![1] }
    first.dispose()
    const next = make()
    await next.start()
    await flushPromises()
    expect(vi.mocked(api.saveCloudReadingState).mock.calls[1]![1]).toEqual(original)
  })
  it('账号和文件修订的未同步缓存互相隔离', async () => {
    const first = make()
    await first.start()
    first.observe(position(.1))
    const other = make('user-2')
    await other.start()
    const revision = make('user-1', 'rev-2')
    await revision.start()
    expect(other.initialPosition.value?.current_percent).toBe(.6)
    expect(revision.initialPosition.value?.current_percent).toBe(.6)
  })
  it('断网初次打开时保留本机阅读，重连已有云端记录须选择，不自动覆盖', async () => {
    vi.mocked(api.createReadingSession).mockRejectedValueOnce(new Error('offline'))
    const reader = make()
    expect(await reader.start()).toBe(false)
    reader.observe(position(.2))
    expect(await reader.start()).toBe(true)
    expect(reader.status.value).toBe('conflict')
    expect(api.saveCloudReadingState).not.toHaveBeenCalled()
    reader.chooseLocal()
    await flushPromises()
    expect(api.saveCloudReadingState).toHaveBeenCalledWith('rev-1', expect.objectContaining({ current_percent: .2, base_version: 3 }), expect.any(AbortSignal))
  })
  it('重复回执之后云端已有更新时再次要求选择，不把旧回执误报为已同步', async () => {
    vi.mocked(api.saveCloudReadingState).mockResolvedValueOnce({ state: { ...cloud, version: 4 }, position_applied: true, duplicate: true })
    vi.mocked(api.getCloudReadingState).mockResolvedValue({ ...cloud, version: 7, current_percent: .9, furthest_percent: .9 })
    const reader = make()
    await reader.start()
    reader.observe(position(.2))
    await reader.flush()
    expect(reader.status.value).toBe('conflict')
    expect(reader.conflict.value?.version).toBe(7)
    expect(localStorage.getItem('atoman:book-reading-outbox:user-1:rev-1')).toContain('0.2')
  })
  it('正文未就绪不计时，隐藏或闲置页面不报告活跃', async () => {
    Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'visible' })
    const reader = make()
    await reader.start()
    await reader.heartbeat()
    expect(api.sendReadingHeartbeat).not.toHaveBeenCalled()
    reader.ready()
    await flushPromises()
    expect(api.sendReadingHeartbeat).toHaveBeenLastCalledWith('session-1', { sequence: 1, visible: true, active: true }, expect.any(AbortSignal))
    await vi.advanceTimersByTimeAsync(61_000)
    await reader.heartbeat()
    expect(vi.mocked(api.sendReadingHeartbeat).mock.calls.at(-1)![1].active).toBe(false)
    Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'hidden' })
    reader.activity()
    await reader.heartbeat()
    expect(vi.mocked(api.sendReadingHeartbeat).mock.calls.at(-1)![1]).toMatchObject({ visible: false, active: false })
  })
  it('卸载取消请求并清理待保存计时器，不再向下一个账号发送写入', async () => {
    const reader = make()
    await reader.start()
    reader.observe(position(.2))
    reader.dispose()
    await vi.advanceTimersByTimeAsync(1000)
    await reader.flush()
    expect(api.saveCloudReadingState).not.toHaveBeenCalled()
    expect(reader.signal.aborted).toBe(true)
  })
})
